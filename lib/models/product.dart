class Product{
  final String name;
  final String description;
  final String image;
  final int price;
  final String unit;
  final int rating;
  final String category;

  const Product({
    required this.name,
    required this.description,
    required this.image,
    required this.price,
    required this.unit,
    required this.rating,
    required this.category,
  });
}